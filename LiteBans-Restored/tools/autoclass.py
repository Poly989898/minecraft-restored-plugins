#!/usr/bin/env python3
"""Proposes class names from data inside the class: Kotlin data-class toString prefixes `Name(field=`, `Name{field=`, and synthetic switch-map holders.
Writes mappings/auto-classes.map (C lines) for classes that still have obfuscated (<=3 char) names."""
import re,glob,os,collections
files={os.path.basename(f)[:-5]:open(f,encoding='utf-8').read() for f in glob.glob('src/main/java/litebans/*.java')}
taken=set(files); out=[]; used=collections.Counter()
def uniq(n):
    base=n; i=2
    while n in taken: n='%s%d'%(base,i); i+=1
    taken.add(n); return n
for n,s in sorted(files.items()):
    if len(n)>3: continue
    new=None
    m=re.search(r'"([A-Z][A-Za-z0-9]{2,})\((?:[a-z]\w*=)',s) or re.search(r'"([A-Z][A-Za-z0-9]{2,})\{(?:[a-z]\w*=)',s)
    if m and 'toString' in s: new=m.group(1)
    elif '// $VF: synthetic class' in s:
        e=re.search(r'new int\[(\w+)\.values\(\)\.length\]',s)
        if e:
            refs=[m for m,t in files.items() if m!=n and re.search(r'\b%s\.\w+\['%re.escape(n),t)]
            new=(refs[0] if len(refs)==1 else e.group(1))+'SwitchMap'
    if new:
        new=re.sub(r'^(Fabric|Kotlin)?','',new) if False else new
        out.append('C %s %s'%(n,uniq(new)))
open('mappings/auto-classes.map','w').write('# generated by tools/autoclass.py\n'+'\n'.join(out)+'\n')
print(len(out),'proposed'); print('\n'.join(out[:60]))
