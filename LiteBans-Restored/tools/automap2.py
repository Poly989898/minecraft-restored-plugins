#!/usr/bin/env python3
"""Field names from data (ResultSet/config column names) and accessor names from field names.
Pass 1 (fields): `this.f_f = <x>.getString("reason")` -> F Class.f_f reason.   Pass 2 (accessors): `T m() { return this.field; }` -> getField/isField,
`void m(T v) { this.field = v; }` -> setField, for fields that already have a readable name.  usage: automap2.py fields|accessors"""
import re,glob,os,sys,collections
mode=sys.argv[1]
fab=set(l.strip()[:-5] for l in open('tools/fabric-files.txt') if l.strip())
files={os.path.basename(f)[:-5]:open(f,encoding='utf-8').read() for f in glob.glob('src/main/java/litebans/*.java') if os.path.basename(f)[:-5] not in fab}
OBFF=re.compile(r'^[a-zA-Z]{1,2}\d?_f$')
def camel(c):
    p=[x for x in re.split(r'[^A-Za-z0-9]+',c) if x]
    r=p[0][:1].lower()+p[0][1:]+''.join(x[:1].upper()+x[1:] for x in p[1:])
    return r if r.isidentifier() else None
out=[]
if mode=='fields':
    for c,s in sorted(files.items()):
        declared=set(re.findall(r'^   (?:private |public |protected )?(?:static )?(?:final )?[\w<>\[\], ]+ (\w+)(?: =|;)',s,re.M))
        seen=set()
        for m in re.finditer(r'this\.(\w+_f) = (?:\([\w<>]+\))?[\w.()]*\.get(?:String|Long|Int|Boolean|Timestamp|Double|Object)\("([A-Za-z_]\w*)"',s):
            f,col=m.group(1),m.group(2); n=camel(col)
            if not n or f in seen or not OBFF.match(f): continue
            if n in declared: n+='Value'
            if n in declared: continue
            seen.add(f); declared.add(n); out.append('F %s.%s %s'%(c,f,n))
else:
    for c,s in sorted(files.items()):
        methods=collections.Counter(re.findall(r'^   (?:@\w+ )*(?:public |protected |private )?(?:static )?(?:final )?[\w<>\[\], .?]+? (\w+)\(',s,re.M))
        used=set(methods)
        for m in re.finditer(r'^   (?:public |protected )?(?:final )?([\w<>\[\], .?]+?) ([a-zA-Z]{1,2}_\d+|[a-zA-Z]{1,2}\d?)\(\) \{\n      return this\.(\w+);\n   \}',s,re.M):
            typ,meth,field=m.groups()
            if OBFF.match(field) or not re.match(r'^[a-z]\w*$',field): continue
            if methods[meth]>1: continue    # overloaded name: Renamer needs the parameter list, skip
            new=('is' if typ=='boolean' else 'get')+field[:1].upper()+field[1:]
            if new in used: continue
            used.add(new); out.append('M %s.%s() %s'%(c,meth,new))
        for m in re.finditer(r'^   (?:public |protected )?(?:final )?(?:void|\w+) ([a-zA-Z]{1,2}_\d+|[a-zA-Z]{1,2}\d?)\(([\w<>\[\], .?]+?) var1\) \{\n      this\.(\w+) = var1;\n(?:      return this;\n)?   \}',s,re.M):
            meth,typ,field=m.groups()
            if OBFF.match(field) or not re.match(r'^[a-z]\w*$',field): continue
            if methods[meth]>1: continue
            new='set'+field[:1].upper()+field[1:]
            if new in used: continue
            used.add(new); out.append('M %s.%s(%s) %s'%(c,meth,re.sub(r'<.*>','',typ).split('.')[-1].strip(),new))
open('mappings/names.map','w').write('# generated by tools/automap2.py %s\n'%mode+'\n'.join(out)+'\n'); print(len(out)); print('\n'.join(out[:15]))
