#!/usr/bin/env python3
"""Derives names from data the plugin itself carries: Message enum constants <- message keys, Settings fields <- config keys.
Writes mappings/auto-names.map (field renames, applied by tools/Renamer.java)."""
import re,collections
out=[]
# Message constants: `   x_f("key", ...)` or `   x_f(CMD, "key", ...)`
s=open('src/main/java/litebans/Message.java',encoding='utf-8').read()
used=set(re.findall(r'^   ([A-Za-z][A-Za-z0-9_]*)[(,;]',s,re.M))
for m in re.finditer(r'^   ([A-Za-z0-9]+_f)\((?:[A-Za-z_.]+, )?"([A-Za-z0-9_.]+)"',s,re.M):
    old,key=m.group(1),m.group(2)
    new=re.sub(r'[^A-Za-z0-9]+','_',key).upper().strip('_')
    if not new or new[0].isdigit(): new='M_'+new
    base=new; i=2
    while new in used: new='%s_%d'%(base,i); i+=1
    used.add(new); out.append('F Message.%s %s'%(old,new))
nm=len(out)
# Settings fields from config keys
s=open('src/main/java/litebans/Settings.java',encoding='utf-8').read()
fields=set(re.findall(r'^   (?:private |public |protected )?(?:final )?[\w<>\[\], ]+ (\w+);',s,re.M))
seen=set(); ns=0
for m in re.finditer(r'this\.(\w+_f) = this\.\w+\.\w+\("([A-Za-z0-9_.]+)"',s):
    old,key=m.group(1),m.group(2)
    if old in seen or not old.endswith('_f'): continue
    parts=[p for p in re.split(r'[._]+',key) if p]
    new=parts[0].lower()+''.join(p[:1].upper()+p[1:].lower() for p in parts[1:])
    if new in fields or not new.isidentifier(): new=new+'Setting'
    if new in fields: continue
    seen.add(old); fields.add(new); out.append('F Settings.%s %s'%(old,new)); ns+=1
open('mappings/auto-names.map','w').write('# generated by tools/automap.py\n'+'\n'.join(out)+'\n')
print('message constants',nm,'settings fields',ns)
