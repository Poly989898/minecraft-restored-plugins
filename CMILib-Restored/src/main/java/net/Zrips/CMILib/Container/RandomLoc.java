package net.Zrips.CMILib.Container;

public class RandomLoc {
  double x = 0.0;
  double y = 0.0;
  double z = 0.0;

  public RandomLoc(double x, double y, double z) {
    this.x = x;
    this.y = y;
    this.z = z;
  }

  public double getX() {
    return this.x;
  }

  public double getY() {
    return this.y;
  }

  public double getZ() {
    return this.z;
  }
}
